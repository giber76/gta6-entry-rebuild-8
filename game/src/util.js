// Seeded RNG + math helpers for Solara Bay (deterministic world).
export function mulberry32(seed) {
  let a = seed >>> 0;
  return function () {
    a |= 0; a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
export const clamp = (v, lo, hi) => (v < lo ? lo : v > hi ? hi : v);
export const lerp = (a, b, t) => a + (b - a) * t;
export const dist2d = (ax, az, bx, bz) => Math.hypot(ax - bx, az - bz);
export const angleTo = (ax, az, bx, bz) => Math.atan2(bx - ax, bz - az);
// forward vector for a heading (x = sin, z = cos), matching the play-test.
export const forwardOf = (h) => ({ x: Math.sin(h), z: Math.cos(h) });
// Normalize an angle to [-PI, PI].
export function angNorm(a) {
  while (a > Math.PI) a -= Math.PI * 2;
  while (a < -Math.PI) a += Math.PI * 2;
  return a;
}
